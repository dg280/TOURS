/**
 * Generate public/sitemap.xml from the `tours` table, so it cannot drift from
 * the pages that actually exist. Runs as `prebuild` (so on every Vercel deploy).
 *
 * URL rule = src/lib/tour-slugs.ts: stored `slug`, else slug of the English title.
 *
 * On Vercel/CI a failure fails the build: shipping a stale sitemap silently is
 * the bug this script exists to prevent. Locally, with no credentials, the
 * committed file is kept and a warning is printed.
 */
import { createClient } from '@supabase/supabase-js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SITE = 'https://toursandetours.eu';
const OUT = fileURLToPath(new URL('../public/sitemap.xml', import.meta.url));

export function toSlug(text) {
    return text
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .toLowerCase()
        .replace(/[&]/g, 'and')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .replace(/-{2,}/g, '-')
        .slice(0, 80);
}

export const tourSlug = (t) => t.slug || toSlug(t.title_en || t.title || '') || String(t.id);

const escapeXml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const alternates = (base) =>
    [
        ['en', base],
        ['fr', `${base}?lang=fr`],
        ['es', `${base}?lang=es`],
        ['x-default', base],
    ]
        .map(([l, href]) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${escapeXml(href)}" />`)
        .join('\n');

export function buildSitemap(tours) {
    const active = tours.filter((t) => t.is_active !== false);
    const slugs = active.map(tourSlug);
    const dupes = slugs.filter((s, i) => slugs.indexOf(s) !== i);
    if (dupes.length) throw new Error(`Duplicate tour slugs: ${[...new Set(dupes)].join(', ')}`);

    const tourEntries = active
        .map((t, i) => {
            const loc = `${SITE}/tours/${slugs[i]}`;
            return `  <url>
    <loc>${escapeXml(loc)}</loc>
${alternates(loc)}
    <changefreq>weekly</changefreq>
    <priority>0.9</priority>
  </url>`;
        })
        .join('\n\n');

    return `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/generate-sitemap.mjs from the tours table. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">

  <url>
    <loc>${SITE}/</loc>
${alternates(`${SITE}/`)}
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
  </url>

  <url>
    <loc>${SITE}/about</loc>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>

${tourEntries}

</urlset>
`;
}

async function main() {
    const strict = Boolean(process.env.VERCEL || process.env.CI);
    const fail = (msg) => {
        if (strict) {
            console.error(`[sitemap] ${msg}`);
            process.exit(1);
        }
        console.warn(`[sitemap] ${msg} - keeping the existing public/sitemap.xml`);
    };

    const url = process.env.VITE_SUPABASE_URL;
    const key = process.env.VITE_SUPABASE_ANON_KEY;
    if (!url || !key) return fail('VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY not set');

    const { data, error } = await createClient(url, key).from('tours').select('*').order('id');
    if (error) return fail(`Supabase error: ${error.message}`);
    if (!data || data.length === 0) return fail('tours table returned no rows');

    const xml = buildSitemap(data);
    let previous = '';
    try { previous = readFileSync(OUT, 'utf8'); } catch { /* first run */ }
    if (xml !== previous) writeFileSync(OUT, xml);
    console.log(`[sitemap] ${data.filter((t) => t.is_active !== false).length} tours -> public/sitemap.xml`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
